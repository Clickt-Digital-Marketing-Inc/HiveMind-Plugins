def _widget_model(ctx: dict, period: str | None, currency: str,
                  brand: str | None, csv_path: str | None, cogs_csv: str | None) -> dict:
    base = _model(ctx, period, currency)   # provenance + rows (reused, no row loss)
    inp = ctx["inputs"]
    cut = _cutoffs(ctx)
    total_rev = base["params"]["total_rev"]
    params = {
        "cogs": inp["cogs_pct"] / 100.0,
        "ship": inp["ship_pct"] / 100.0,
        "proc": inp["proc_pct"] / 100.0,
        "fixed": float(inp.get("fixed_costs") or 0),
        "total_rev": total_rev,
        "exc": cut["exc"], "high": cut["high"], "avg": cut["avg"], "low": cut["low"],
    }
    prov = dict(base["provenance"])
    prov["title"] = "CM3 by product" + (f" — {period}" if period else "")
    date = _dt.date.today().isoformat()
    slug = re.sub(r"[^a-z0-9]+", "-", (brand or "").lower()).strip("-")
    stem = "cm3-by-product" + (("_" + slug) if slug else "") + "_" + date
    save = {
        "skill": "cm3-by-product-report",
        "brand": brand or "CM3 by product",
        "filename_stem": stem,
        "csv": csv_path or "",
        "cogs_csv": cogs_csv or "",
    }
    return {"provenance": prov, "params": params,
            "summary": _widget_summary(ctx), "rows": base["rows"], "save": save}


