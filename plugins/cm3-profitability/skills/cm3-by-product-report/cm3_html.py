def chart_rows(ctx: dict) -> list:
    """Rows the static chart render consumes: the explorer's embedded row dicts
    augmented with the Python model's computed cm3/cm3_pct/band at the default
    params — the same augmentation the live JS applies via rowsComputed().
    Model row order is preserved (deterministic)."""
    products = ctx["products"]
    rows = []
    for p in products:
        rows.append({
            "t": p.title,
            "camp": p.campaign or "(no campaign)",
            "ven": p.vendor or "",
            "src": p.cogs_source,
            "impr": p.impr,
            "clicks": p.clicks,
            "cost": p.cost,
            "conv": p.conv,
            "rev": p.conv_value,
            "cogs": p.cogs_pct,
            "cm1": p.cm1,
            "cm2": p.cm2,
            "cm3": p.cm3,
            "cm3_pct": p.cm3_pct,
            "band": p.band,
        })
    return rows


def render_static_charts(ctx: dict, *, only: str | None = None) -> list:
    """Render the declared charts to SVG at the model's default params via the
    vendored chart module. Returns [(chart_id, title, svg), ...]. Hard-fails
    (SystemExit 2) with a clear message if vl-convert-python is missing."""
    return _charts.render_spec_charts({"rows": chart_rows(ctx)}, {"charts": CHARTS}, only=only)


def _cutoffs(ctx: dict) -> dict:
    """Resolved band cutoffs as {exc,high,avg,low} fractions, from ctx or defaults."""
    c = ctx.get("cutoffs") or {}
    inp = ctx.get("inputs") or {}
    g = lambda k: float(c.get(k, inp.get(k, _DEFAULT_CUTOFFS[k])))
    return {"exc": g("band_exc"), "high": g("band_high"), "avg": g("band_avg"), "low": g("band_low")}


def _vendor_cogs_map(ctx: dict) -> dict:
    """Resolved per-vendor COGS% exactly as build_vendor_rollup shows it:
    the Shopify-lookup value if present, else the blanket fallback. Keyed by
    the vendor's display name (first-seen order preserved)."""
    look = ctx.get("cogs_look")
    fallback = ctx.get("fallback_cogs")
    if fallback is None:
        fallback = float((ctx.get("inputs") or {}).get("cogs_pct", 0)) / 100.0
    out: dict = {}
    for p in ctx["products"]:
        if p.vendor and p.vendor not in out:
            vc = look.by_vendor.get(p.vendor.lower().strip()) if look is not None else None
            out[p.vendor] = vc if vc is not None else fallback
    return out


def _model(ctx: dict, period: str | None, currency: str) -> dict:
    products = ctx["products"]
    total_rev = sum(p.conv_value for p in products)
    rows = [
        {
            "t": p.title,
            "camp": p.campaign or "(no campaign)",
            "catL": list(p.cat),      # 5 category levels ('' where absent)
            "ptL": list(p.ptype),     # 5 product-type levels
            "ven": p.vendor or "",
            "src": p.cogs_source,
            "impr": p.impr,
            "clicks": p.clicks,
            "cost": p.cost,
            "conv": p.conv,
            "rev": p.conv_value,
            "cogs": p.cogs_pct,
        }
        for p in products
    ]
    inp = ctx["inputs"]
    return {
        "provenance": {
            "period": period or "unknown",
            "currency": currency,
            "generated": _dt.datetime.now().isoformat(timespec="seconds"),
            "n": len(rows),
            "cogs_mode": "Per-product (Shopify GP CSV)" if ctx.get("cogs_look") else f"{inp['cogs_pct']}% blanket",
        },
        "params": {
            "ship": inp["ship_pct"] / 100.0,
            "proc": inp["proc_pct"] / 100.0,
            "fixed": float(inp.get("fixed_costs") or 0),
            "total_rev": total_rev,
            "cutoffs": _cutoffs(ctx),
        },
        "vcogs": _vendor_cogs_map(ctx),
        "srcmix": dict(ctx.get("cogs_source_counts") or {}),
        "rows": rows,
    }


